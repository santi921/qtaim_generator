"""Write qtaim_gen/source/core/esp_contract.py: straight-line McMurchie-Davidson recursion and
contraction for Hermite orders 3-6, used by esp._esp_e_blocked. Generated as a module (not
exec at import) so numba can cache it.

usage: python scripts/gen_esp_contract.py [--check]   (--check: exit 1 if the file differs)
"""

import os
import sys

from qtaim_gen.source.core.esp_hermite import NTRI, OP_C, OP_DIR, OP_S1, OP_S2

ORDERS = (3, 4, 5, 6)
OUT = os.path.join(os.path.dirname(__file__), "..", "qtaim_gen", "source", "core", "esp_contract.py")


def contraction(N):
    nt = [int(v) for v in NTRI]
    lines = [
        "@njit(nogil=True, cache=True, error_model=\"numpy\")",
        f"def contract{N}(nb, X, Y, Z, F, D, base, pk, p, acc):",
        f"    \"\"\"acc[i] += pk sum_q D[base + q] R^0_q(X[i], Y[i], Z[i]) for Hermite order {N}.\"\"\"",
    ]
    lines += [f"    d{q} = pk * D[base + {q}]" for q in range(nt[N])]
    lines.append("    f0 = 1.0")
    lines += [f"    f{m} = f{m - 1} * (-2.0 * p)" for m in range(1, N + 1)]
    lines.append("    for i in range(nb):")
    lines.append("        x = X[i]")
    lines.append("        y = Y[i]")
    lines.append("        z = Z[i]")
    lines += [f"        r{m}_0 = f{m} * F[{m}, i]" for m in range(N + 1)]
    for m in range(N - 1, -1, -1):
        for q in range(1, nt[N - m]):
            e = f"{'xyz'[int(OP_DIR[q])]} * r{m + 1}_{int(OP_S1[q])}"
            if OP_S2[q] >= 0:
                e += f" + {float(OP_C[q])!r} * r{m + 1}_{int(OP_S2[q])}"
            lines.append(f"        r{m}_{q} = {e}")
    terms = [f"d{q} * r0_{q}" for q in range(nt[N])]
    lines.append("        acc[i] += (" + terms[0])
    lines += [f"                   + {t}" for t in terms[1:]]
    lines[-1] += ")"
    return "\n".join(lines)


def source():
    head = ('"""Generated by scripts/gen_esp_contract.py; do not edit. Straight-line Hermite Coulomb\n'
            'recursion (R^m_tuv from F_m, MD downward in m) and contraction with the density-weighted\n'
            'Hermite coefficients, vectorized over a block of points, for orders 3-6."""\n\n'
            "from numba import njit\n")
    return head + "".join("\n\n" + contraction(N) + "\n" for N in ORDERS)


if __name__ == "__main__":
    text = source()
    if "--check" in sys.argv:
        with open(OUT) as f:
            sys.exit(0 if f.read() == text else 1)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(OUT)}")
