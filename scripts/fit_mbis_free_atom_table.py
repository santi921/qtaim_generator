"""Fit free-atom MBIS shell parameters, the initial guess of the charge engine's
converged MBIS mode, and write qtaim_gen/source/data/mbis_free_atom.py.

Per element (Z 1-103): the spherical MBIS model rho0(r) = sum_k N_k / (8 pi s_k^3)
exp(-r / s_k) is fitted to the free-atom radial density the engine already ships
(multiwfn_atmraddens, the Hirshfeld proatoms), by the MBIS fixed-point iteration
on a log-spaced radial grid. The shell count starts from Multiwfn's period rule
(mbis_initial_shells); shells whose widths converge within MERGE of each other
are merged and shells below DROP electrons removed, then the fit is repeated
(the treatment denspart applies to its own free-atom table).

    python scripts/fit_mbis_free_atom_table.py [--check_denspart PATH_TO_denspart/mbis.py]
"""
import argparse
import ast
import os

import numpy as np

from qtaim_gen.source.core.charge_engine import mbis_initial_shells
from qtaim_gen.source.data import multiwfn_atmraddens as R

TOL = 1e-12  # largest population change (e) per iteration
MAXIT = 200000
MERGE = 1e-4  # relative width difference below which two shells are merged
DROP = 1e-4  # e
OUT = os.path.join(os.path.dirname(__file__), "..", "qtaim_gen", "source", "data", "mbis_free_atom.py")


def radial_grid(z):
    """Fine log-spaced grid with trapezoid weights 4 pi r^2 dr, and the free-atom
    density on it (log-log interpolation of the shipped table)."""
    rtab = np.array(R.RADPOS)
    rho = np.array(R.RHO[z])
    rtab = rtab[: len(rho)]
    r = np.geomspace(1e-7, rtab[-1], 20000)
    lr = np.interp(np.log(r), np.log(rtab), np.log(rho))
    dens = np.exp(lr)
    w = 4 * np.pi * r**2 * np.gradient(r)
    return r, w, dens


def fit(r, w, dens, pop, sig):
    for it in range(1, MAXIT + 1):
        shells = pop[:, None] / (8 * np.pi * sig[:, None] ** 3) * np.exp(-r[None, :] / sig[:, None])
        rho0 = shells.sum(axis=0)
        frac = np.divide(shells, rho0, out=np.zeros_like(shells), where=rho0 > 0)
        pn = (w * dens * frac).sum(axis=1)
        sn = (w * dens * frac * r).sum(axis=1) / (3 * pn)
        done = np.abs(pn - pop).max() < TOL
        pop, sig = pn, sn
        if done:
            return pop, sig, it
    return pop, sig, MAXIT


def reduce(pop, sig):
    keep = pop > DROP
    pop, sig = pop[keep], sig[keep]
    order = np.argsort(sig)
    pop, sig = pop[order], sig[order]
    out_p, out_s = [pop[0]], [sig[0]]
    for p, s in zip(pop[1:], sig[1:]):
        if abs(s - out_s[-1]) / s < MERGE:
            tot = out_p[-1] + p
            out_s[-1] = (out_p[-1] * out_s[-1] + p * s) / tot
            out_p[-1] = tot
        else:
            out_p.append(p)
            out_s.append(s)
    return np.array(out_p), np.array(out_s)


def fit_element(z):
    r, w, dens = radial_grid(z)
    m, p0, s0 = mbis_initial_shells(np.array([z]))
    pop, sig = p0[0, : m[0]].astype(float), s0[0, : m[0]].astype(float)
    total = 0
    notes = []
    while True:
        pop, sig, it = fit(r, w, dens, pop, sig)
        total += it
        p2, s2 = reduce(pop, sig)
        if len(p2) == len(pop):
            break
        notes.append(f"{len(pop)} -> {len(p2)} shells")
        pop, sig = p2, s2
    order = np.argsort(sig)
    pop, sig = pop[order], sig[order]
    kl = float((w * dens * np.log(dens / (pop[:, None] / (8 * np.pi * sig[:, None] ** 3)
                                           * np.exp(-r[None, :] / sig[:, None])).sum(axis=0))).sum())
    return pop, sig, total, notes, kl, float((w * dens).sum())


def load_denspart(path):
    src = open(path).read()
    i = src.index("INITIAL_MBIS_PARAMETERS = {")
    j = src.index("\n}", i) + 2
    return ast.literal_eval(src[i + len("INITIAL_MBIS_PARAMETERS = "):j])


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check_denspart", help="denspart mbis.py, to compare against (read as data only)")
    args = p.parse_args()
    table, lines = {}, []
    for z in sorted(R.RHO):
        pop, sig, it, notes, kl, n = fit_element(z)
        table[z] = [(round(float(a), 6), round(float(b), 8)) for a, b in zip(pop, sig)]
        lines.append(f"Z {z:3d}: {len(pop)} shells, {it:6d} iterations, N {n:.5f}, KL/N {kl / n:.5f} {' '.join(notes)}")
        print(lines[-1], flush=True)
    with open(OUT, "w") as f:
        f.write('"""Free-atom MBIS shell parameters, generated by scripts/fit_mbis_free_atom_table.py:\n'
                "per Z, (population, width in Bohr) of each shell, innermost first, fitted to the\n"
                'free-atom densities in multiwfn_atmraddens. Do not edit by hand."""\n\nSHELLS = {\n')
        for z, shells in table.items():
            f.write(f"    {z}: {shells},\n")
        f.write("}\n")
    print(f"wrote {OUT}")
    if args.check_denspart:
        ref = load_denspart(args.check_denspart)
        print("\nZ | shells ours/denspart | max |dN| (e) | max rel |d width|")
        for z, shells in table.items():
            if z not in ref:
                continue
            ours = np.array(shells)
            theirs = np.array(sorted(((n, 1 / a) for n, a in ref[z]), key=lambda t: t[1]))
            if len(ours) != len(theirs):
                print(f"{z} | {len(ours)}/{len(theirs)} | - | -")
                continue
            print(f"{z} | {len(ours)}/{len(theirs)} | {np.abs(ours[:, 0] - theirs[:, 0]).max():.3f} | "
                  f"{(np.abs(ours[:, 1] - theirs[:, 1]) / theirs[:, 1]).max():.3f}")


if __name__ == "__main__":
    main()
