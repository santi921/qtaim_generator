"""IBSI and Laplacian bond order: engine vs Multiwfn on the same orca.wfx.

Per job: orca.wfx from the job's molden (or gbw through orca_2mkl) with core/wavefunction.py;
Multiwfn IBSI at grid options 4 (75 x 434, the engine's grid) and 1 (30 x 110, production) and
the Laplacian bond order (45 x 302); then the charge engine at full_set 2 on the same file.

    python campaign.py one JOB_DIR OUT_ROOT --src SRC --multiwfn PATH [--orca_2mkl PATH] [--nthreads 8]
    python campaign.py summarize OUT_ROOT

`one` writes OUT_ROOT/<JOB_DIR relative to SRC>/result.json and keeps the Multiwfn outputs
next to it; a job with a result.json is skipped. IBSI is compared on Int(dg_pair), which does
not depend on the H2 reference value; the reference each Multiwfn build prints is recorded.
"""

import argparse
import glob
import json
import os
import re
import resource
import shutil
import subprocess
import sys
import time

STDIN = {
    "ibsi_g4": "9\n10\n1\n4\n0\n0\nq\n",
    "ibsi_g1": "9\n10\n1\n1\n0\n0\nq\n",
    "lbo": "9\n8\nn\n0\nq\n",
}
IBSI_ROW = re.compile(
    r"^\s*(\d+)\((\w+)\s*\)\s*(\d+)\((\w+)\s*\)\s+Dist:\s*(\S+)\s+Int\(dg_pair\):\s*(\S+)\s+IBSI:\s*(\S+)")
IBSI_REF_LINE = re.compile(r"Set H2 reference value, current:\s*(\S+)")
LBO_ROW = re.compile(r"#\s*\d+:\s*(\d+)\((\w+)\s*\)\s*(\d+)\((\w+)\s*\):\s*(\S+)")
VERSION_LINE = re.compile(r"update date:\s*(\S+)")


def parse_ibsi(path):
    rows, ref, build = {}, None, None
    for line in open(path, errors="replace"):
        m = IBSI_ROW.match(line)
        if m:
            rows[f"{m[1]}_{m[2]}_to_{m[3]}_{m[4]}"] = (float(m[6]), float(m[7]))
        if ref is None and (r := IBSI_REF_LINE.search(line)):
            ref = float(r[1])
        if build is None and (v := VERSION_LINE.search(line)):
            build = v[1]
    return rows, ref, build


def parse_lbo(path):
    out, on = {}, False
    for line in open(path, errors="replace"):
        if "The bond orders >=" in line:
            on = True
            continue
        if on:
            m = LBO_ROW.search(line)
            if not m:
                break
            out[f"{m[1]}_{m[2]}_to_{m[3]}_{m[4]}"] = float(m[5])
    return out


def unlimited_stack():
    resource.setrlimit(resource.RLIMIT_STACK, (resource.RLIM_INFINITY, resource.RLIM_INFINITY))


def make_wfx(job, wd, orca_2mkl):
    from qtaim_gen.source.core.wavefunction import read_orca_molden, write_wfx

    if os.path.exists(os.path.join(wd, "orca.wfx")):
        return
    moldens = sorted(glob.glob(os.path.join(job, "*.molden.input")))
    if moldens:
        shutil.copy(moldens[0], wd)
        molden = os.path.join(wd, os.path.basename(moldens[0]))
    else:
        gbws = [g for g in sorted(glob.glob(os.path.join(job, "*.gbw*"))) if not re.search(r"_atom\d", g)]
        if not gbws or not orca_2mkl:
            raise FileNotFoundError(f"no molden, or gbw without --orca_2mkl, in {job}")
        g = gbws[0]
        base = os.path.basename(g).removesuffix(".zstd0")
        if g.endswith(".zstd0"):
            subprocess.run(["unzstd", "-f", "-o", os.path.join(wd, base), g], check=True)
        else:
            shutil.copy(g, wd)
        subprocess.run([orca_2mkl, base.removesuffix(".gbw"), "-molden"], cwd=wd, check=True)
        molden = os.path.join(wd, base.removesuffix(".gbw") + ".molden.input")
    w = read_orca_molden(molden)
    write_wfx(w, os.path.join(wd, "orca.wfx"), title="Generated by qtaim_generator (core/wavefunction.py)")
    for leftover in [molden] + glob.glob(os.path.join(wd, "*.gbw")):
        os.remove(leftover)


def one(args):
    import numpy as np

    from qtaim_gen.source.core import charge_engine as ce
    from qtaim_gen.source.core.omol import write_settings_file
    from qtaim_gen.source.core.qtaim_engine import IBSI_REF

    job = os.path.abspath(args.job)
    rel = os.path.relpath(job, os.path.abspath(args.src))
    wd = os.path.join(args.out_root, rel)
    if os.path.exists(os.path.join(wd, "result.json")):
        print("done already:", rel)
        return
    os.makedirs(wd, exist_ok=True)
    make_wfx(job, wd, args.orca_2mkl)
    write_settings_file(wd, n_threads=args.nthreads)

    rec = {"job": rel}
    for key, stdin in STDIN.items():
        out = os.path.join(wd, f"{key}.out")
        if not os.path.exists(out):
            t0 = time.perf_counter()
            with open(out, "w") as f:
                subprocess.run([args.multiwfn, "orca.wfx"], input=stdin, text=True, stdout=f,
                               stderr=subprocess.STDOUT, cwd=wd, preexec_fn=unlimited_stack,
                               env=dict(os.environ, OMP_STACKSIZE="1G"))
            rec[f"mw_{key}_s"] = time.perf_counter() - t0
    g4, ref4, build = parse_ibsi(os.path.join(wd, "ibsi_g4.out"))
    g1, ref1, _ = parse_ibsi(os.path.join(wd, "ibsi_g1.out"))
    lbo_ref = parse_lbo(os.path.join(wd, "lbo.out"))
    rec.update({"mw_build": build, "mw_ref": ref4})

    wfx = ce.read_wfx(os.path.join(wd, "orca.wfx"))
    t0 = time.perf_counter()
    out = ce.run(os.path.join(wd, "orca.wfx"), full_set=2, mbis_mode="multiwfn")
    rec["engine_s"] = time.perf_counter() - t0
    meta = out["_meta"]
    rec.update({"natoms": len(wfx["atnums"]), "ibsi_s": meta["timings_s"].get("ibsi"),
                "lbo_s": meta["timings_s"].get("laplacian_bond"),
                "skipped": [s["schemes"] for s in meta["skipped"]]})
    idx = {lab: i for i, lab in enumerate(ce.atom_labels(wfx["atnums"]))}

    eng_i = out.get("ibsi_bond")
    if eng_i is not None:
        d2 = {}
        for k in eng_i:
            a, b = (idx[s] for s in k.split("_to_"))
            d2[k] = (np.linalg.norm(wfx["coords"][a] - wfx["coords"][b]) * ce.B2A) ** 2
        eng_int = {k: v * IBSI_REF * d2[k] for k, v in eng_i.items()}
        rec["ibsi_pairs"] = len(eng_i)
        rec["ibsi_keys_equal"] = set(eng_i) == set(g4)
        rec["ibsi_int_max"] = max((abs(eng_int[k] - v[0]) for k, v in g4.items() if k in eng_int), default=0.0)
        rec["ibsi_int_worst"] = max(((abs(eng_int[k] - v[0]), k) for k, v in g4.items() if k in eng_int),
                                    default=(0.0, None))[1]
        # the grid change alone: production values at the engine's normalization
        same = {k: v[1] * ref1 / IBSI_REF for k, v in g1.items()}
        diffs = [abs(eng_i[k] - v) for k, v in same.items() if k in eng_i]
        rels = [abs(eng_i[k] - v) / abs(v) for k, v in same.items() if k in eng_i and abs(v) >= 0.05]
        rec["grid_vs_g1_max"] = max(diffs, default=0.0)
        rec["grid_vs_g1_rel_max"] = max(rels, default=0.0)
        rec["grid_vs_g1_rel_median"] = float(np.median(rels)) if rels else 0.0
    eng_l = out.get("laplacian_bond")
    if eng_l is not None:
        common = set(eng_l) & set(lbo_ref)
        rec["lbo_keys_equal"] = set(eng_l) == set(lbo_ref)
        rec["lbo_only_engine"] = {k: eng_l[k] for k in set(eng_l) - set(lbo_ref)}
        rec["lbo_only_mw"] = {k: lbo_ref[k] for k in set(lbo_ref) - set(eng_l)}
        rec["lbo_max"] = max((abs(eng_l[k] - lbo_ref[k]) for k in common), default=0.0)
    with open(os.path.join(wd, "result.json"), "w") as f:
        json.dump(rec, f, indent=1)
    print(rel, {k: rec.get(k) for k in ("ibsi_keys_equal", "ibsi_int_max", "lbo_keys_equal", "lbo_max")}, flush=True)


def summarize(args):
    import numpy as np

    recs = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(args.out_root, "**", "result.json"),
                                                         recursive=True))]
    print("jobs", len(recs), "| Multiwfn builds", sorted({str(r.get("mw_build")) for r in recs}),
          "| H2 references", sorted({str(r.get("mw_ref")) for r in recs}))
    skips = {}
    for r in recs:
        for s in r["skipped"]:
            skips[s] = skips.get(s, 0) + 1
    print("skipped schemes:", skips or "none")
    ib = [r for r in recs if "ibsi_int_max" in r]
    if ib:
        a = np.array([r["ibsi_int_max"] for r in ib])
        print(f"ibsi | jobs {len(ib)} | pair sets equal {sum(r['ibsi_keys_equal'] for r in ib)} | "
              f"Int(dg_pair) max {a.max():.2e} median {np.median(a):.2e} | above 5e-6: {(a > 5e-6 + 1e-9).sum()}")
        worst = max(ib, key=lambda r: r["ibsi_int_max"])
        print(f"  worst: {worst['job']} {worst['ibsi_int_worst']}")
        g = np.array([r["grid_vs_g1_rel_max"] for r in ib])
        print(f"  grid vs production 30 x 110 (same reference), relative over IBSI >= 0.05: per-job max "
              f"median {np.median(g):.3f}, max {g.max():.3f}; per-job median median "
              f"{np.median([r['grid_vs_g1_rel_median'] for r in ib]):.3f}")
    lb = [r for r in recs if "lbo_max" in r]
    if lb:
        b = np.array([r["lbo_max"] for r in lb])
        print(f"laplacian_bond | jobs {len(lb)} | pair sets equal {sum(r['lbo_keys_equal'] for r in lb)} | "
              f"max {b.max():.2e} median {np.median(b):.2e} | above 5e-7: {(b > 5e-7 + 1e-9).sum()}")
        for r in lb:
            if not r["lbo_keys_equal"]:
                print("  pair set differs:", r["job"], "engine only", r["lbo_only_engine"], "Multiwfn only",
                      r["lbo_only_mw"])
    for key in ("ibsi_s", "mw_ibsi_g1_s", "mw_ibsi_g4_s", "lbo_s", "mw_lbo_s", "engine_s"):
        v = [r[key] for r in recs if r.get(key) is not None]
        if v:
            print(f"{key}: median {np.median(v):.2f} s, max {max(v):.1f} s, total {sum(v):.0f} s")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    o = sub.add_parser("one")
    o.add_argument("job")
    o.add_argument("out_root")
    o.add_argument("--src", required=True)
    o.add_argument("--multiwfn", required=True)
    o.add_argument("--orca_2mkl")
    o.add_argument("--nthreads", type=int, default=8)
    s = sub.add_parser("summarize")
    s.add_argument("out_root")
    args = p.parse_args()
    one(args) if args.cmd == "one" else summarize(args)


if __name__ == "__main__":
    sys.exit(main())
