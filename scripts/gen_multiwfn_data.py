"""Generate qtaim_gen/source/data modules from the Multiwfn 3.8 Fortran source.

    python scripts/gen_multiwfn_data.py ~/dev/Multiwfn_src/Multiwfn_3.8_src_Linux qtaim_gen/source/data

Writes three modules (Tian Lu confirmed the tables may be redistributed):
  multiwfn_atmraddens.py  free-atom radial densities (atmraddens.f90) and atmrhocut
                          (define.f90): the Hirshfeld promolecule
  multiwfn_edf.py         EDF core densities as s Gaussians (edflib.f90; Zou, Cai and
                          Wang's Molden2AIM library), keyed by (Z, ncore)
  multiwfn_sphcart.py     spherical -> Cartesian matrices for .molden input
                          (sub.f90 gensphcartab, iprog=2)

multiwfn_tables.py and lebedev_tables.py were generated by scripts that were not
kept; they are not rebuilt here.
"""

import math
import os
import re
import sys
import textwrap


def _f(s):
    return float(s.replace("D", "e").replace("d", "e"))


def _read(src, name):
    with open(os.path.join(src, name), encoding="latin-1") as fh:
        return fh.read().replace("\r", "")


def _fmt(vals, indent="    ", width=96):
    return textwrap.indent(textwrap.fill(", ".join(repr(v) for v in vals), width), indent)


def atmraddens(src):
    txt = _read(src, "atmraddens.f90")
    pos = {int(i): _f(v) for i, v in re.findall(r"posarr\(\s*(\d+)\)=\s*([-0-9.DdEe+]+)", txt)}
    assert sorted(pos) == list(range(1, 201)), len(pos)
    start = txt.index("subroutine genatmraddens(")
    end = txt.index("end subroutine", start)
    rho, npt, cur = {}, {}, None
    for line in txt[start:end].splitlines():
        m = re.search(r"iele\s*==\s*(\d+)\s*\)", line)
        if m:
            cur = int(m.group(1))
            rho[cur] = {}
            continue
        m = re.match(r"\s*npt\s*=\s*(\d+)", line)
        if m and cur:
            npt[cur] = int(m.group(1))
            continue
        m = re.match(r"\s*rhoarr\(\s*(\d+)\)\s*=\s*([-0-9.DdEe+]+)", line)
        if m and cur:
            rho[cur][int(m.group(1))] = _f(m.group(2))
    assert sorted(rho) == list(range(1, 104)), sorted(rho)[-3:]
    for z in rho:
        assert sorted(rho[z]) == list(range(1, npt[z] + 1)), (z, npt[z], len(rho[z]))
    d = _read(src, "define.f90")
    m = re.search(r"real\*8 :: atmrhocut\(0:nelesupp\)=\(/(.*?)/\)", d, re.S)
    body = re.sub(r"!.*", "", m.group(1)).replace("&", " ")
    cut = []
    for tok in re.findall(r"\([^()]*\)|[^,\s]+", body):
        mm = re.match(r"\(\s*([^,]+),\s*\w+\s*=\s*(\w+)\s*,\s*(\w+)\s*\)", tok)
        if mm:
            hi = 150 if mm.group(3) == "nelesupp" else int(mm.group(3))
            cut += [_f(mm.group(1))] * (hi - int(mm.group(2)) + 1)
        else:
            cut.append(_f(tok))
    assert len(cut) == 151, len(cut)
    out = ['"""Spherically averaged free-atom radial densities built into Multiwfn 3.8\n'
           '(atmraddens.f90 genatmradpos/genatmraddens; atmrhocut from define.f90).\n\n'
           'H-Lr (Z=1..103), neutral ground states; see the comment block in atmraddens.f90\n'
           'for the level of theory per element. Values are as tabulated (Bohr, e/Bohr^3),\n'
           'truncated by Multiwfn at 1e-8. Generated by parsing the Fortran source, so do\n'
           'not hand-edit. Used by charge_engine_worker.py for the Hirshfeld promolecule.\n"""\n\n']
    out.append("# shared radial grid (Bohr), atmradpos(1..200)\nRADPOS = (\n" + _fmt([pos[i] for i in range(1, 201)]) + ",\n)\n\n")
    out.append("# beyond this radius (Bohr) Multiwfn returns zero density, atmrhocut(0..150)\nATMRHOCUT = (\n" + _fmt(cut) + ",\n)\n\n")
    out.append("# rho on RADPOS[:npt] per element\nRHO = {\n")
    for z in range(1, 104):
        out.append(f"    {z}: (\n" + textwrap.indent(_fmt([rho[z][i] for i in range(1, npt[z] + 1)]), "    ") + ",\n    ),\n")
    out.append("}\n")
    return "".join(out)


def edf(src):
    txt = _read(src, "edflib.f90")
    num = r"[-+]?\d+\.\d+D[-+]\d+"
    tables = {}
    for sub in re.finditer(r"subroutine EDFLIB(\d\d)\(iz,nfun,alf,coe\)(.*?)end\s*\n", txt, re.S):
        ncore = int(sub.group(1))
        for case in re.finditer(r"case\((\d+)\)(.*?)(?=case\(|end select)", sub.group(2), re.S):
            z, b = int(case.group(1)), case.group(2)
            nfun = int(re.search(r"nfun\s*=\s*(\d+)", b).group(1))
            alf = [_f(x) for x in re.findall(num, re.search(r"alf\(1:nfun\)=\(/(.*?)/\)", b, re.S).group(1))]
            coe = [_f(x) for x in re.findall(num, re.search(r"coe\(1:nfun\)=\(/(.*?)/\)", b, re.S).group(1))]
            assert len(alf) == nfun == len(coe), (ncore, z, nfun, len(alf), len(coe))
            tables[(z, ncore)] = (alf, coe)
    assert tables, "no EDFLIB subroutines found"
    out = ['"""EDF core densities built into Multiwfn 3.8 (edflib.f90, the Molden2AIM library\n'
           'of Zou, Cai and Wang, version 5): the density of the core electrons an ECP\n'
           'removes, as s Gaussians. Key (Z, ncore) -> (exponents, coefficients), Bohr^-2\n'
           'and the coefficient of each normalized-free s Gaussian exp(-a r^2). Multiwfn\n'
           'attaches the entry for (Z, Z - effective charge) to every ECP atom (fileIO.f90\n'
           'readEDFlib). Generated by parsing the Fortran source, so do not hand-edit.\n"""\n\n'
           'EDF = {\n']
    for (z, nc), (a, c) in sorted(tables.items()):
        out.append(f"    ({z}, {nc}): (\n        (\n{_fmt(a, ' ' * 12, 92)},\n        ),\n"
                   f"        (\n{_fmt(c, ' ' * 12, 92)},\n        ),\n    ),\n")
    out.append("}\n")
    return "".join(out)


def sphcart(src):
    """gensphcartab with iprog=2 (.molden): rows are Cartesian functions in the
    order Multiwfn's comments give per shell, columns the spherical functions
    0, +1, -1, +2, -2, ..."""
    txt = _read(src, "sub.f90")
    start = txt.index("subroutine gensphcartab(")
    body = txt[start:txt.index("end subroutine", start)]
    shape = {"matd": (6, 5), "matf": (10, 7), "matg": (15, 9), "math": (21, 11)}
    mats = {k: [[0.0] * c for _ in range(r)] for k, (r, c) in shape.items()}
    branch = None
    for raw in body.splitlines():
        line = raw.split("!")[0].strip()
        if line.startswith("if (iprog==1)"):
            branch = 1
            continue
        if line.startswith("else if (iprog==2)"):
            branch = 2
            continue
        if line == "end if":
            branch = None
            continue
        if branch == 1:
            continue
        m = re.match(r"(mat[dfgh])\((\d+)(?::(\d+))?,(\d+)\)=(.*)$", line)
        if not m:
            continue
        name, r0, r1, col, expr = m.group(1), int(m.group(2)), m.group(3), int(m.group(4)), m.group(5)
        expr = re.sub(r"(\d+(?:\.\d+)?)D0", r"\1", expr).replace("sqrt", "math.sqrt")
        if r1:
            vals = eval(expr.replace("(/", "(").replace("/)", ")"), {"math": math})
            for k, v in enumerate(vals):
                mats[name][r0 - 1 + k][col - 1] = float(v)
        else:
            mats[name][r0 - 1][col - 1] = float(eval(expr, {"math": math}))
    for name, m in mats.items():
        assert all(any(row[c] for row in m) for c in range(shape[name][1])), f"{name}: empty column"
    out = ['"""Spherical -> Cartesian transformation matrices Multiwfn 3.8 uses for .molden\n'
           'input (sub.f90 gensphcartab, iprog=2). Row = Cartesian function in the order\n'
           'gensphcartab documents for each shell, column = spherical function in the order\n'
           '0, +1, -1, +2, -2, ... Generated by parsing the Fortran source, so do not\n'
           'hand-edit. Used by core/wavefunction.py.\n"""\n\n']
    for name, label in (("matd", "D"), ("matf", "F"), ("matg", "G"), ("math", "H")):
        rows = ",\n".join("    (" + ", ".join(repr(v) for v in row) + ")" for row in mats[name])
        out.append(f"{label} = (\n{rows},\n)\n\n")
    return "".join(out).rstrip("\n") + "\n"


def main(argv):
    src, dst = argv[1], argv[2]
    for name, gen in (("multiwfn_atmraddens.py", atmraddens), ("multiwfn_edf.py", edf), ("multiwfn_sphcart.py", sphcart)):
        path = os.path.join(dst, name)
        with open(path, "w") as fh:
            fh.write(gen(src))
        print("wrote", path)


if __name__ == "__main__":
    main(sys.argv)
